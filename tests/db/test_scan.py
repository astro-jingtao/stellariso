"""Offline tests for the two-state scanner.

Everything runs against synthetic mini-databases under pytest's
tmp_path: products are written with known payloads and known
isochrone-block counts, and the scanner's classification is asserted
product by product. The four-state vocabulary of the former
PARSEC-only scanner is pinned here through its two-state mapping
(complete → complete; log_only → incomplete, linear missing; refetch →
incomplete, manual review; pending → incomplete, all parts missing).
"""

from __future__ import annotations

import gzip
import json
from pathlib import Path

import pytest

from stellariso.database.scan import (
    render_markdown,
    render_summary,
    report_json,
    scan_database,
)
from stellariso.models.parsec import blueprint as bp
from stellariso.models.parsec.cmd_form import CmdFieldSet
from stellariso.models.parsec.design import count_blocks

WEB = bp.TRACK_SETS["v1.2S_COLIBRI_web"]
V20 = bp.TRACK_SETS["v2.0"]
S35 = bp.TRACK_SETS["v1.2S_COLIBRI_S35"]


def _expected(cell: bp.Cell, which: str = "log") -> dict[str, str]:
    fields = cell.log_fields() if which == "log" else cell.linear_fields()
    return CmdFieldSet.from_overrides(**fields).as_dict()


def _write_product(
    db: Path,
    set_key: str,
    label: str,
    payload: dict[str, str],
    blocks: int = 177,
    table: str = "output.dat",
    *,
    with_record: bool = True,
    gzip_table: bool = False,
) -> Path:
    directory = db / "parsec" / set_key / label
    directory.mkdir(parents=True, exist_ok=True)
    text = "# File generated by CMD 3.9\n" + "# Zini MH logAge Mini\n" * blocks + "1.0 2.0\n"
    raw = gzip.compress(text.encode()) if gzip_table else text.encode()
    (directory / table).write_bytes(raw)
    if with_record:
        record = {"request_fields": payload, "output": {"sha256": "0" * 64}}
        (directory / (table + ".record.json")).write_text(
            json.dumps(record), encoding="utf-8"
        )
    return directory


@pytest.fixture()
def db(tmp_path: Path) -> Path:
    return tmp_path


def _parsec(report):
    return report.families["parsec"]


class TestBlockCounting:
    def test_plain_and_gzip_by_content(self, tmp_path: Path):
        text = "# head\n" + "# Zini MH\n" * 3 + "1 2\n"
        plain = tmp_path / "plain.dat"
        plain.write_text(text, encoding="utf-8")
        zipped = tmp_path / "zipped.dat"  # server keeps the .dat name
        zipped.write_bytes(gzip.compress(text.encode()))
        assert count_blocks(plain) == 3
        assert count_blocks(zipped) == 3

    def test_missing_file(self, tmp_path: Path):
        assert count_blocks(tmp_path / "nope.dat") is None


class TestTwoStateClassification:
    def test_conforming_log_product_is_incomplete_log_only(self, db: Path):
        cell = bp.Cell(set=WEB, mh=0.0, omega=0.0)
        _write_product(db, WEB.key, cell.label, _expected(cell), blocks=177)
        scan = scan_database(db).families["parsec"].products[cell.set.key + "/" + cell.label]
        assert scan.state == "incomplete"
        assert scan.parts["log"].kind == "ok"
        assert scan.parts["linear"].kind == "missing"
        assert not scan.needs_review

    def test_both_grids_conforming_is_complete(self, db: Path):
        cell = bp.Cell(set=WEB, mh=-2.2, omega=0.0)
        _write_product(db, WEB.key, cell.label, _expected(cell), blocks=177)
        _write_product(
            db, WEB.key, cell.label, _expected(cell, "linear"),
            blocks=bp.expected_linear_ages(),
            table="output_linear.dat",
        )
        scan = scan_database(db).families["parsec"].products[cell.set.key + "/" + cell.label]
        assert scan.state == "complete"
        assert scan.detail() == "complete"

    def test_coarse_age_sampling_is_nonconforming_manual_review(self, db: Path):
        cell = bp.Cell(set=S35, mh=0.0, omega=0.0)
        coarse = dict(_expected(cell), isoc_dlage="0.05")
        _write_product(db, S35.key, cell.label, coarse, blocks=71)
        family = scan_database(db).families["parsec"]
        scan = family.products[cell.set.key + "/" + cell.label]
        assert scan.state == "incomplete"
        assert scan.needs_review
        assert scan.parts["log"].kind == "nonconforming"
        assert scan.parts["linear"].kind == "missing"
        reasons = " ; ".join(scan.parts["log"].reasons)
        assert "isoc_dlage" in reasons
        assert "71 isochrones" in reasons and "177" in reasons
        # nonconforming data is never auto-refetched: no fetch planned
        assert (scan, "linear") not in [
            (s, p) for s, p in family.auto_fetches()
        ]

    def test_wrong_block_count_is_nonconforming(self, db: Path):
        cell = bp.Cell(set=WEB, mh=0.3, omega=0.0)
        _write_product(db, WEB.key, cell.label, _expected(cell), blocks=100)
        scan = scan_database(db).families["parsec"].products[cell.set.key + "/" + cell.label]
        assert scan.state == "incomplete" and scan.needs_review
        assert any("100 isochrones" in r for r in scan.parts["log"].reasons)

    def test_missing_record_is_nonconforming_not_superseded(self, db: Path):
        cell = bp.Cell(set=WEB, mh=-1.0, omega=0.0)
        _write_product(db, WEB.key, cell.label, {}, with_record=False)
        report = scan_database(db)
        scan = report.families["parsec"].products[cell.set.key + "/" + cell.label]
        assert scan.parts["log"].kind == "nonconforming"
        assert any("no acquisition record" in r for r in scan.parts["log"].reasons)
        assert report.families["parsec"].superseded == []

    def test_incomplete_payload_reasons_carry_missing_fields(self, db: Path):
        cell = bp.Cell(set=WEB, mh=0.5, omega=0.0)
        payload = {k: v for k, v in _expected(cell).items() if k != "imf_file"}
        _write_product(db, WEB.key, cell.label, payload)
        scan = scan_database(db).families["parsec"].products[cell.set.key + "/" + cell.label]
        assert scan.parts["log"].kind == "nonconforming"
        assert any("imf_file" in r for r in scan.parts["log"].reasons)

    def test_aux_product_is_superseded(self, db: Path):
        cell = bp.Cell(set=WEB, mh=0.0, omega=0.0)
        payload = dict(_expected(cell), imf_file="tab_imf/imf_salpeter.dat", isoc_dlage="0.1")
        _write_product(db, WEB.key, "aux_imf_salpeter", payload, blocks=36)
        family = scan_database(db).families["parsec"]
        assert cell.set.key + "/" + cell.label not in family.products or (
            family.products[cell.set.key + "/" + cell.label].state == "incomplete"
        )
        assert len(family.superseded) == 1
        assert family.superseded[0]["reason"].startswith("option-variation")

    def test_non_canonical_eta_cell_classified(self, db: Path):
        # eta = 0.0 is a fetch-stage axis value: a conforming product
        # lands in its own designed cell (label suffix _e0.0).
        cell = bp.Cell(set=WEB, mh=0.0, omega=0.0, eta=0.0)
        assert cell.label == "mh_p0.0_e0.0"
        _write_product(db, WEB.key, cell.label, _expected(cell))
        scan = scan_database(db).families["parsec"].products[cell.set.key + "/" + cell.label]
        assert scan.parts["log"].kind == "ok"

    def test_non_fetch_axis_value_counts_beyond_target(self, db: Path):
        # A canonical-axis cell with a non-canonical dust combination is
        # designed but outside the fetch-stage target: archived beyond
        # target, never counted in the committed status.
        cell = bp.Cell(set=WEB, mh=0.0, omega=0.0, dust_m="nodustM", dust_c="nodustC")
        _write_product(db, WEB.key, cell.label, _expected(cell))
        family = scan_database(db).families["parsec"]
        counts = family.counts()
        assert counts == {"complete": 0, "incomplete": 471}  # the dust cell is not among them
        beyond = family.archived_beyond_target()
        assert [s.design.label for s in beyond] == [cell.label]

    def test_eta_variant_on_v20_maps_to_no_cell(self, db: Path):
        # v2.0 eta is inert: the design pins it at the canonical value,
        # so an archived eta-variant payload maps to no designed cell.
        cell = bp.Cell(set=V20, mh=0.0, omega=0.0)
        payload = dict(_expected(cell), eta_reimers="0.4")
        _write_product(db, V20.key, "mh_p0.0_e0.4", payload)
        family = scan_database(db).families["parsec"]
        assert family.superseded[0]["reason"] == "maps to no designed cell"

    def test_directory_label_parses_axis_suffixes(self, db: Path):
        cell = bp.Cell(set=WEB, mh=-1.0, omega=0.0, eta=0.4, n_intpc=5,
                       dust_m="AlOx", dust_c="gra", lpv="2")
        # no record: the directory name alone must reconstruct the cell
        _write_product(db, WEB.key, cell.label, {}, with_record=False)
        scan = scan_database(db).families["parsec"].products[cell.set.key + "/" + cell.label]
        assert scan.parts["log"].kind == "nonconforming"

    def test_omega_cells_incomplete_until_fetched(self, db: Path):
        cell = bp.Cell(set=V20, mh=0.0, omega=0.4)
        _write_product(db, V20.key, cell.label, _expected(cell), blocks=177)
        scan = scan_database(db).families["parsec"].products["v2.0/mh_p0.0_w0.40"]
        assert scan.parts["log"].kind == "ok"
        assert scan.state == "incomplete"

    def test_boundary_cells_exist_and_are_all_missing(self, db: Path):
        report = scan_database(db)  # empty database
        products = report.families["parsec"].products
        assert products["v2.0/mh_m2.19"].state == "incomplete"
        assert products["v2.0/mh_p0.34"].state == "incomplete"
        assert products["v1.2S_COLIBRI_S35/mh_m1.4921"].state == "incomplete"

    def test_directory_outside_blueprint_sets(self, db: Path):
        (db / "parsec" / "mystery_release" / "mh_p0.0").mkdir(parents=True)
        family = scan_database(db).families["parsec"]
        assert len(family.superseded) == 1
        assert family.superseded[0]["reason"] == "directory outside the blueprint sets"

    def test_payload_directory_disagreement_is_superseded_and_blocked(self, db: Path):
        cell = bp.Cell(set=WEB, mh=-1.0, omega=0.0)
        other = bp.Cell(set=WEB, mh=-1.2, omega=0.0)
        _write_product(db, WEB.key, cell.label, _expected(other))
        family = scan_database(db).families["parsec"]
        assert len(family.superseded) == 1
        assert "payload says cell" in family.superseded[0]["reason"]
        # the designed product whose directory holds foreign data is
        # blocked, not silently re-fetched into
        scan = family.products[cell.set.key + "/" + cell.label]
        assert scan.blocked_reason is not None
        assert scan.needs_review

    def test_duplicate_directory_is_superseded(self, db: Path):
        cell = bp.Cell(set=WEB, mh=-1.0, omega=0.0)
        _write_product(db, WEB.key, cell.label, _expected(cell))
        # a second directory of the same set claiming the cell by payload
        _write_product(db, WEB.key, "mh_m1.0_copy", _expected(cell))
        family = scan_database(db).families["parsec"]
        reasons = [e["reason"] for e in family.superseded]
        assert any(r.startswith("duplicate directory") for r in reasons)

    def test_gzipped_archived_table_scanned(self, db: Path):
        cell = bp.Cell(set=V20, mh=-2.1, omega=0.0)
        _write_product(db, V20.key, cell.label, _expected(cell), gzip_table=True)
        scan = scan_database(db).families["parsec"].products[cell.set.key + "/" + cell.label]
        assert scan.parts["log"].kind == "ok"


class TestFourStateConversion:
    """The old vocabulary's mapping onto the two states, one synthetic
    product per old state."""

    def test_matrix(self, db: Path):
        complete = bp.Cell(set=WEB, mh=0.0, omega=0.0)
        log_only = bp.Cell(set=WEB, mh=-0.5, omega=0.0)
        refetch = bp.Cell(set=WEB, mh=-1.5, omega=0.0)
        # pending: mh -2.0 has nothing on disk
        _write_product(db, WEB.key, complete.label, _expected(complete))
        _write_product(
            db, WEB.key, complete.label, _expected(complete, "linear"),
            blocks=bp.expected_linear_ages(), table="output_linear.dat",
        )
        _write_product(db, WEB.key, log_only.label, _expected(log_only))
        _write_product(
            db, WEB.key, refetch.label,
            dict(_expected(refetch), isoc_dlage="0.05"), blocks=71,
        )
        report = scan_database(db)
        products = report.families["parsec"].products
        assert products[WEB.key + "/" + complete.label].state == "complete"
        scan = products[WEB.key + "/" + log_only.label]
        assert scan.state == "incomplete" and scan.parts["linear"].kind == "missing"
        scan = products[WEB.key + "/" + refetch.label]
        assert scan.state == "incomplete" and scan.needs_review
        assert products[WEB.key + "/mh_m2.0"].state == "incomplete"
        assert products[WEB.key + "/mh_m2.0"].missing_parts == ["log", "linear"]


class TestAggregates:
    def test_counts_and_auto_fetches(self, db: Path):
        web_cell = bp.Cell(set=WEB, mh=0.0, omega=0.0)
        _write_product(db, WEB.key, web_cell.label, _expected(web_cell))
        coarse_cell = bp.Cell(set=S35, mh=0.0, omega=0.0)
        _write_product(
            db, S35.key, coarse_cell.label,
            dict(_expected(coarse_cell), isoc_dlage="0.05"), blocks=71,
        )
        report = scan_database(db)
        # web fetch target = 28 [M/H] x 3 fetch-stage eta values = 84
        assert report.families["parsec"].counts() == {
            "complete": 0,
            "incomplete": 471,
        }
        fetches = report.auto_fetches("parsec")
        # primary: web = 1 log-only (1 linear fetch) + 83 pending (2 each);
        # v2.0 = 297 pending. secondary: the coarse S35 cell contributes
        # NOTHING automatically (manual review); the other 14 S35 cells
        # and 5 sets x 15 sparse cells are pending.
        assert len(fetches) == (1 + 83 * 2 + 297 * 2) + (14 * 2 + 5 * 15 * 2)

    def test_totals_shape(self, db: Path):
        report = scan_database(db)  # empty database
        totals = report.totals()
        assert totals["complete"] == 0
        assert totals["incomplete"] == 471 + 6  # parsec target + mist packages
        assert totals["missing_part_fetches"] == 942 + 6  # submissions + downloads
        # the mist family of an empty database is 6 missing packages
        assert report.families["mist"].counts() == {"complete": 0, "incomplete": 6}


class TestMistFamilyScan:
    def test_complete_mist_product(self, db: Path, monkeypatch):
        from stellariso.integrity import sha256_file
        from stellariso.models.mist.design import MistAdapter

        adapter = MistAdapter()
        design = next(
            d
            for d in adapter.designs()
            if d.collection == "1.2" and d.label == "vvcrit0.4_full_isos"
        )
        directory = db / "mist" / "1.2" / design.label
        directory.mkdir(parents=True)
        archive = directory / design.parts[0].filename
        archive.write_bytes(b"payload")
        manifest = {
            "schema": "stellariso-manifest/2",
            "family": "mist",
            "release": "1.2",
            "label": design.label,
            "parts": {"archive": {"file": archive.name, "sha256": sha256_file(archive)}},
        }
        (directory / "MANIFEST.json").write_text(json.dumps(manifest), encoding="utf-8")
        report = scan_database(db)
        family = report.families["mist"]
        scan = family.products[design.key]
        assert scan.state == "complete"
        assert scan.parts["archive"].kind == "ok"
        # the catalog size (692 MB) differs from the 7-byte payload: warning
        assert scan.parts["archive"].warnings


class TestRendering:
    def test_markdown_carries_full_declarations(self, db: Path):
        cell = bp.Cell(set=WEB, mh=0.0, omega=0.0)
        _write_product(db, WEB.key, cell.label, _expected(cell))
        text = render_markdown(scan_database(db))
        assert "-2.2 to +0.5, step 0.1 dex -> 28 values" in text
        assert "6.6 to 10.13 dex, step 0.02 dex -> 177 isochrones" in text
        assert "1.0e5 to 4.0e6 yr" in text and "40 isochrones" in text
        assert "Reimers eta: 0.0 to 0.5, step 0.1 -> 6 values" in text
        assert "TP-cycle resolution n_inTPC: 5, 10, 20 -> 3 values" in text
        assert "5 O-rich x 4 C-rich = 20 combinations" in text
        assert "LPV prescription: 1, 2, 3, 4 -> 4 values" in text
        assert "Designed 162,468 products" in text
        assert cell.set.key + "/" + cell.label in text
        assert "incomplete (log ok; linear missing)" in text
        assert "never deleted" in text or "never auto-refetched" in text

    def test_markdown_lists_manual_review(self, db: Path):
        cell = bp.Cell(set=WEB, mh=0.0, omega=0.0)
        _write_product(
            db, WEB.key, cell.label,
            dict(_expected(cell), isoc_dlage="0.05"), blocks=71,
        )
        text = render_markdown(scan_database(db))
        assert "manual review — 1" in text
        assert "isoc_dlage" in text

    def test_summary_digest(self, db: Path):
        cell = bp.Cell(set=WEB, mh=0.0, omega=0.0)
        _write_product(db, WEB.key, cell.label, _expected(cell))
        text = render_summary(scan_database(db))
        assert "parsec: 471 committed products" in text
        assert "incomplete 471" in text
        assert "mist: 6 committed products" in text

    def test_json_machine_report(self, db: Path):
        cell = bp.Cell(set=WEB, mh=0.0, omega=0.0)
        _write_product(db, WEB.key, cell.label, _expected(cell))
        machine = report_json(scan_database(db))
        entry = machine["families"]["parsec"]["products"][WEB.key + "/" + cell.label]
        assert entry["state"] == "incomplete"
        assert entry["parts"]["linear"]["kind"] == "missing"
        assert machine["families"]["parsec"]["committed"] == 471
        # parsec: 942 - 1 linear landed; mist of the synthetic db: 6 downloads
        assert machine["totals"]["missing_part_fetches"] == 941 + 6
