"""Version-anchored reading of real CMD 3.9 isochrone tables.

Fixtures: the real single-block capture ``output_table.dat``, the derived
synthetic multi-block grid ``output_grid.dat`` (see the fixture README),
and the header-only failure shape ``output_empty.dat``.
"""

from __future__ import annotations

import io
from pathlib import Path

import pytest

from stellariso.exceptions import (
    DataIntegrityError,
    UnrecognizedFormatError,
    UnsupportedReleaseError,
)
from stellariso.facade import ParsecIso, construct
from stellariso.grid import IsochroneGrid
from stellariso.models.parsec.backend import read_parsec
from stellariso.models.parsec.reader import parse_parsec_cmd

FIXTURES = Path(__file__).parent.parent / "data" / "parsec" / "cmd_form"
REAL = FIXTURES / "output_table.dat"
GRID = FIXTURES / "output_grid.dat"
EMPTY = FIXTURES / "output_empty.dat"
RELEASE = "v1.2S +  COLIBRI S_37 + S_35 + PR16"


class TestRealTable:
    def test_dispatch_is_anchored_to_the_version_echo(self):
        parsed = parse_parsec_cmd(REAL)
        assert parsed.format == "cmd_table_3_9"
        assert parsed.facts["cmd_version"] == "3.9"

    def test_header_facts(self):
        facts = parse_parsec_cmd(REAL).facts
        assert facts["release"] == RELEASE
        assert facts["eta_reimers"] == 0.2
        assert facts["photsys"] == "UBVRIJHK"
        assert facts["imf"].startswith("Kroupa (2001, 2002)")

    def test_block_carries_per_row_keying_columns(self):
        parsed = parse_parsec_cmd(REAL)
        assert len(parsed.blocks) == 1
        block = parsed.blocks[0]
        assert block.z == 0.0152
        assert block.mh == pytest.approx(0.01508, abs=1e-5)
        assert parsed.facts["ages"] == (9.0,)

    def test_native_columns_are_the_real_vocabulary(self):
        native = parse_parsec_cmd(REAL).native
        names = native.table.colnames
        for expected in (
            "Zini", "MH", "logAge", "Mini", "int_IMF", "Mass", "logL",
            "logTe", "logg", "label", "McoreTP", "C_O", "pmode", "Mloss",
            "tau1m", "X", "Y", "mbolmag",
        ):
            assert expected in names

    def test_unified_layer_over_the_real_names(self):
        set_ = read_parsec(REAL)
        iso = set_.isochrones[0]
        assert iso.selection == {"log_age": 9.0, "initial_z": 0.0152}
        assert float(iso.native["logg"][0]) == 5.191
        assert iso.unified["log_surface_gravity"][0] == 5.191
        assert iso.unified["initial_mass"][0] == pytest.approx(0.09)
        assert iso.unified["current_mass"][0] == pytest.approx(0.09)
        assert iso.unified["phase"][0] == "pre_main_sequence"
        # the real layout has no logMdot: no unified mass-loss-rate field
        assert "log_mass_loss_rate" not in iso.unified
        assert "Mloss" in iso.native

    def test_facade_over_the_real_capture(self):
        parsec = construct(f"parsec/{RELEASE}", paths=[REAL])
        assert isinstance(parsec, ParsecIso)
        logg = parsec.get_logg(mass=0.5, log_age=9.0, initial_z=0.0152)
        assert 4.0 < logg < 5.0

    def test_parameters_resolve_for_the_3_9_product(self):
        iso = read_parsec(REAL).isochrones[0]
        assert iso.parameter("initial_z").values == (0.0152,)
        assert iso.parameter("initial_helium").role.value == "derived"
        assert iso.parameter("eta_reimers").value == 0.2


class TestMultiBlockGrid:
    def test_three_blocks_two_axes(self):
        grid = IsochroneGrid([read_parsec(GRID)])
        assert len(grid) == 3
        assert grid.axes == {
            "log_age": (9.0, 9.5),
            "initial_z": (0.0001, 0.0152),
        }

    def test_selection_pins_both_coordinates(self):
        grid = IsochroneGrid([read_parsec(GRID)])
        iso = grid.get_isochrone(log_age=9.5, initial_z=0.0152)
        assert iso.selection["log_age"] == 9.5
        with pytest.raises(Exception, match="initial_z"):
            grid.get_isochrone(log_age=9.5)

    def test_each_block_repeats_the_column_line(self):
        parsed = parse_parsec_cmd(GRID)
        assert parsed.blocks  # the first block carries the file-level line
        for block in parsed.blocks:
            assert any(
                "Zini" in ln and "Mini" in ln for ln in block.header_lines
            )

    def test_multi_value_z_and_ages_in_one_set(self):
        parsed = parse_parsec_cmd(GRID)
        assert parsed.facts["ages"] == (9.0, 9.5, 9.0)
        assert {b.z for b in parsed.blocks} == {0.0001, 0.0152}


class TestRefusals:
    def test_header_only_capture_raises(self):
        with pytest.raises(UnrecognizedFormatError, match="no data rows"):
            parse_parsec_cmd(EMPTY)

    def test_unknown_version_echo_refused(self):
        text = REAL.read_text(encoding="utf-8").replace(
            "File generated by CMD 3.9", "File generated by CMD 4.0"
        )
        with pytest.raises(UnsupportedReleaseError, match="4.0"):
            parse_parsec_cmd(io.StringIO(text))

    def test_non_isochrone_output_refused(self):
        text = REAL.read_text(encoding="utf-8").replace(
            "# Kind of output: isochrone tables",
            "# Kind of output: luminosity function",
        )
        with pytest.raises(UnrecognizedFormatError, match="luminosity function"):
            parse_parsec_cmd(io.StringIO(text))

    def test_block_with_deviating_columns_refused(self, tmp_path):
        lines = GRID.read_text(encoding="utf-8").splitlines()
        # swap one block's column line to a deviating vocabulary
        seen = 0
        for i, ln in enumerate(lines):
            if ln.startswith("#") and "Zini" in ln and "Mini" in ln:
                seen += 1
                if seen == 2:
                    lines[i] = ln.replace(" logg ", " log_g ")
                    break
        bad = tmp_path / "deviating.dat"
        bad.write_text("\n".join(lines) + "\n", encoding="utf-8")
        with pytest.raises(DataIntegrityError, match="declares columns"):
            parse_parsec_cmd(bad)

    def test_version_echo_beats_column_signature(self):
        # a documented-layout file that somehow carries a 3.9 echo must go
        # to the 3.9 parser (and fail there), not to the legacy reader
        legacy = (
            Path(__file__).parent.parent / "data" / "parsec"
            / "parsec_cmd_v1p2S_fixture.dat"
        ).read_text(encoding="utf-8")
        text = "# File generated by CMD 3.9 (http://stev.oapd.inaf.it/cmd)\n" + legacy
        with pytest.raises(UnrecognizedFormatError):
            parse_parsec_cmd(io.StringIO(text))
