"""Offline tests for the blueprint status scanner.

Everything runs against synthetic mini-databases under pytest's tmp_path:
products are written with known payloads and known isochrone-block
counts, and the scanner's classification is asserted cell by cell.
"""

from __future__ import annotations

import gzip
import json
from pathlib import Path

import pytest

from stellariso.models.parsec import blueprint as bp
from stellariso.models.parsec.cmd_form import CmdFieldSet
from stellariso.models.parsec.blueprint_status import (
    count_blocks,
    render_markdown,
    render_summary,
    scan_database,
)

WEB = bp.TRACK_SETS["v1.2S_COLIBRI_web"]
V20 = bp.TRACK_SETS["v2.0"]
S35 = bp.TRACK_SETS["v1.2S_COLIBRI_S35"]


def _expected(cell: bp.Cell, which: str = "log") -> dict[str, str]:
    fields = cell.log_fields() if which == "log" else cell.linear_fields()
    return CmdFieldSet.from_overrides(**fields).as_dict()


def _write_product(
    db: Path,
    set_key: str,
    label: str,
    payload: dict[str, str],
    blocks: int = 177,
    table: str = "output.dat",
    *,
    with_record: bool = True,
    gzip_table: bool = False,
) -> Path:
    directory = db / "parsec" / set_key / label
    directory.mkdir(parents=True, exist_ok=True)
    text = "# File generated by CMD 3.9\n" + "# Zini MH logAge Mini\n" * blocks + "1.0 2.0\n"
    raw = gzip.compress(text.encode()) if gzip_table else text.encode()
    (directory / table).write_bytes(raw)
    if with_record:
        record = {"request_fields": payload, "output": {"sha256": "0" * 64}}
        (directory / (table + ".record.json")).write_text(
            json.dumps(record), encoding="utf-8"
        )
    return directory


@pytest.fixture()
def db(tmp_path: Path) -> Path:
    (tmp_path / "database.json").write_text("{}", encoding="utf-8")
    return tmp_path


class TestBlockCounting:
    def test_plain_and_gzip_by_content(self, tmp_path: Path):
        text = "# head\n" + "# Zini MH\n" * 3 + "1 2\n"
        plain = tmp_path / "plain.dat"
        plain.write_text(text, encoding="utf-8")
        zipped = tmp_path / "zipped.dat"  # server keeps the .dat name
        zipped.write_bytes(gzip.compress(text.encode()))
        assert count_blocks(plain) == 3
        assert count_blocks(zipped) == 3

    def test_missing_file(self, tmp_path: Path):
        assert count_blocks(tmp_path / "nope.dat") is None


class TestClassification:
    def test_conforming_log_product_is_log_only(self, db: Path):
        cell = bp.Cell(set=WEB, mh=0.0, omega=0.0)
        _write_product(db, WEB.key, cell.label, _expected(cell), blocks=177)
        report = scan_database(db)
        assert report.cells[WEB.key][cell.label].status == "log_only"

    def test_both_grids_conforming_is_complete(self, db: Path):
        cell = bp.Cell(set=WEB, mh=-2.2, omega=0.0)
        payload = _expected(cell)
        _write_product(db, WEB.key, cell.label, payload, blocks=177)
        _write_product(
            db, WEB.key, cell.label, _expected(cell, "linear"),
            blocks=bp.expected_linear_ages(),
            table="output_linear.dat",
        )
        report = scan_database(db)
        assert report.cells[WEB.key][cell.label].status == "complete"

    def test_coarse_age_sampling_is_refetch(self, db: Path):
        cell = bp.Cell(set=S35, mh=0.0, omega=0.0)
        coarse = dict(_expected(cell), isoc_dlage="0.05")
        _write_product(db, S35.key, cell.label, coarse, blocks=71)
        report = scan_database(db)
        scan = report.cells[S35.key][cell.label]
        assert scan.status == "refetch"
        reasons = " ; ".join(scan.reasons)
        assert "isoc_dlage" in reasons
        assert "71 isochrones" in reasons and "177" in reasons

    def test_wrong_block_count_is_refetch(self, db: Path):
        cell = bp.Cell(set=WEB, mh=0.3, omega=0.0)
        _write_product(db, WEB.key, cell.label, _expected(cell), blocks=100)
        report = scan_database(db)
        scan = report.cells[WEB.key][cell.label]
        assert scan.status == "refetch"
        assert any("100 isochrones" in r for r in scan.reasons)

    def test_missing_record_is_refetch_not_superseded(self, db: Path):
        cell = bp.Cell(set=WEB, mh=-1.0, omega=0.0)
        _write_product(db, WEB.key, cell.label, {}, with_record=False)
        report = scan_database(db)
        scan = report.cells[WEB.key][cell.label]
        assert scan.status == "refetch"
        assert any("no acquisition record" in r for r in scan.reasons)
        assert report.superseded == []

    def test_incomplete_payload_flags_gap_and_refetch(self, db: Path):
        cell = bp.Cell(set=WEB, mh=0.5, omega=0.0)
        payload = {k: v for k, v in _expected(cell).items() if k != "imf_file"}
        _write_product(db, WEB.key, cell.label, payload)
        report = scan_database(db)
        assert report.cells[WEB.key][cell.label].status == "refetch"
        assert len(report.payload_gaps) == 1
        assert any("imf_file" in r for r in report.cells[WEB.key][cell.label].reasons)

    def test_aux_product_is_superseded(self, db: Path):
        cell = bp.Cell(set=WEB, mh=0.0, omega=0.0)
        payload = dict(_expected(cell), imf_file="tab_imf/imf_salpeter.dat", isoc_dlage="0.1")
        _write_product(db, WEB.key, "aux_imf_salpeter", payload, blocks=36)
        report = scan_database(db)
        assert report.cells[WEB.key][cell.label].status == "pending"
        assert len(report.superseded) == 1
        assert report.superseded[0]["reason"].startswith("option-variation")

    def test_non_canonical_eta_cell_classified(self, db: Path):
        # eta = 0.0 is a fetch-stage axis value: a conforming product
        # lands in its own designed cell (label suffix _e0.0).
        cell = bp.Cell(set=WEB, mh=0.0, omega=0.0, eta=0.0)
        assert cell.label == "mh_p0.0_e0.0"
        _write_product(db, WEB.key, cell.label, _expected(cell))
        report = scan_database(db)
        assert report.cells[WEB.key][cell.label].status == "log_only"

    def test_non_fetch_axis_value_outside_target_counts(self, db: Path):
        # A canonical-axis cell with a non-canonical dust combination is
        # designed but outside the fetch-stage target: it never appears
        # in the set's target status counts.
        cell = bp.Cell(set=WEB, mh=0.0, omega=0.0, dust_m="nodustM", dust_c="nodustC")
        _write_product(db, WEB.key, cell.label, _expected(cell))
        report = scan_database(db)
        assert report.cells[WEB.key][cell.label].status == "log_only"
        counts = report.counts(WEB.key)
        assert counts["log_only"] == 0 and counts["pending"] == 84

    def test_eta_variant_on_v20_maps_to_no_cell(self, db: Path):
        # v2.0 eta is inert: the design pins it at the canonical value,
        # so an archived eta-variant payload maps to no designed cell.
        cell = bp.Cell(set=V20, mh=0.0, omega=0.0)
        payload = dict(_expected(cell), eta_reimers="0.4")
        _write_product(db, V20.key, "mh_p0.0_e0.4", payload)
        report = scan_database(db)
        assert report.superseded[0]["reason"] == "maps to no designed cell"

    def test_directory_label_parses_axis_suffixes(self, db: Path):
        cell = bp.Cell(set=WEB, mh=-1.0, omega=0.0, eta=0.4, n_intpc=5,
                       dust_m="AlOx", dust_c="gra", lpv="2")
        # no record: the directory name alone must reconstruct the cell
        _write_product(db, WEB.key, cell.label, {}, with_record=False)
        report = scan_database(db)
        assert report.cells[WEB.key][cell.label].status == "refetch"

    def test_omega_cells_pending_until_fetched(self, db: Path):
        cell = bp.Cell(set=V20, mh=0.0, omega=0.4)
        _write_product(db, V20.key, cell.label, _expected(cell), blocks=177)
        report = scan_database(db)
        assert report.cells[V20.key]["mh_p0.0_w0.40"].status == "log_only"

    def test_boundary_cells_exist_and_are_pending(self, db: Path):
        report = scan_database(db)  # empty database
        assert report.cells[V20.key]["mh_m2.19"].status == "pending"
        assert report.cells[V20.key]["mh_p0.34"].status == "pending"
        assert report.cells[S35.key]["mh_m1.4921"].status == "pending"

    def test_directory_outside_blueprint_sets(self, db: Path):
        (db / "parsec" / "mystery_release" / "mh_p0.0").mkdir(parents=True)
        report = scan_database(db)
        assert len(report.superseded) == 1
        assert report.superseded[0]["reason"] == "directory outside the blueprint sets"

    def test_payload_directory_disagreement_is_superseded(self, db: Path):
        cell = bp.Cell(set=WEB, mh=-1.0, omega=0.0)
        other = bp.Cell(set=WEB, mh=-1.2, omega=0.0)
        _write_product(db, WEB.key, cell.label, _expected(other))
        report = scan_database(db)
        assert len(report.superseded) == 1
        assert "payload says cell" in report.superseded[0]["reason"]

    def test_gzipped_archived_table_scanned(self, db: Path):
        cell = bp.Cell(set=V20, mh=-2.1, omega=0.0)
        _write_product(db, V20.key, cell.label, _expected(cell), gzip_table=True)
        report = scan_database(db)
        assert report.cells[V20.key][cell.label].status == "log_only"


class TestAggregates:
    def test_counts_and_jobs(self, db: Path):
        web_cell = bp.Cell(set=WEB, mh=0.0, omega=0.0)
        _write_product(db, WEB.key, web_cell.label, _expected(web_cell))
        coarse_cell = bp.Cell(set=S35, mh=0.0, omega=0.0)
        _write_product(
            db, S35.key, coarse_cell.label,
            dict(_expected(coarse_cell), isoc_dlage="0.05"), blocks=71,
        )
        report = scan_database(db)
        # web fetch target = 28 [M/H] x 3 fetch-stage eta values = 84
        assert report.counts(WEB.key) == {"complete": 0, "log_only": 1, "refetch": 0, "pending": 83}
        # S35 sparse target = 5 [M/H] x 3 eta = 15 cells: one refetch (the
        # coarse product at canonical eta), the other 14 pending.
        assert report.counts(S35.key) == {"complete": 0, "log_only": 0, "refetch": 1, "pending": 14}
        jobs = report.jobs_to_target()
        # primary: web = 1 log-only (1 linear job) + 83 pending (2 jobs
        # each); v2.0 = 297 pending (eta inert, no multiplication).
        assert jobs["primary"] == 1 + 83 * 2 + 297 * 2
        # secondary: S35 = 1 refetch + 14 pending target cells; the five
        # other sets' sparse targets (15 cells each) fully pending.
        assert jobs["secondary"] == (1 * 2 + 14 * 2) + 5 * 15 * 2

    def test_totals_shape(self, db: Path):
        report = scan_database(db)
        totals = report.tier_totals()
        assert totals["primary"]["target"] == 84 + 297
        assert totals["secondary"]["target"] == 6 * 15
        assert totals["primary"]["pending"] == 84 + 297
        assert totals["secondary"]["pending"] == 90


class TestRendering:
    def test_markdown_carries_full_declarations(self, db: Path):
        cell = bp.Cell(set=WEB, mh=0.0, omega=0.0)
        _write_product(db, WEB.key, cell.label, _expected(cell))
        text = render_markdown(scan_database(db))
        assert "-2.2 to +0.5, step 0.1 dex -> 28 values" in text
        assert "6.6 to 10.13 dex, step 0.02 dex -> 177 isochrones" in text
        assert "1.0e5 to 4.0e6 yr" in text and "40 isochrones" in text
        assert "v2.0" in text and "0.99" in text
        assert "Reimers eta: 0.0 to 0.5, step 0.1 -> 6 values" in text
        assert "TP-cycle resolution n_inTPC: 5, 10, 20 -> 3 values" in text
        assert "5 O-rich x 4 C-rich = 20 combinations" in text
        assert "LPV prescription: 1, 2, 3, 4 -> 4 values" in text
        assert "162468 designed cells" in text
        assert "Log grid only" in text and cell.label in text
        assert "Marked data is never deleted" in text

    def test_markdown_lists_only_target_pending(self, db: Path):
        # Beyond-target designed cells are summarized, never listed
        # (the full design has tens of thousands of pending cells).
        text = render_markdown(scan_database(db))
        assert "Pending within the fetch-stage target — 84" in text
        assert "Beyond the fetch-stage target:" in text

    def test_summary_digest(self, db: Path):
        cell = bp.Cell(set=WEB, mh=0.0, omega=0.0)
        _write_product(db, WEB.key, cell.label, _expected(cell))
        text = render_summary(scan_database(db))
        assert "v1.2S_COLIBRI_web (primary)" in text
        assert "log_only 1" in text
        assert "submissions to target" in text
