"""Regenerate the format-equivalent PARSEC CMD fixture (documented layout).

Why synthetic: real CMD 3.9 outputs use a different, per-row-keyed column
vocabulary (see tests/data/parsec/cmd_form/ for real 3.9 captures read by
the anchored `_read_cmd_3_9` parser). This fixture mirrors the OLDER
DOCUMENTED format — column layout from the Girardi isochrone readme
"TABLES OF ISOCHRONES" section (pleiadi.oapd.inaf.it/isoc_photsys.02/
readme.txt) plus the CMD updates stated on the official help page (FLUM
replaced by int_IMF; C/O, M_hec, logMdot, label added) — with
hand-computed rows. Files in this layout carry no `File generated by CMD`
version echo; the reader accepts them by their M_ini/M_act column
signature. It is parser test data, NOT science data.

Run:  python make_parsec_fixture.py   (writes parsec_cmd_v1p2S_fixture.dat)
"""

from __future__ import annotations

from pathlib import Path

import numpy as np

# Header block modeled on a real server-generated one (CMD request for
# parsec_CAF09_v1.2S + COLIBRI S_37+S_35+PR16, UBVRIJHK, no extinction),
# minus the CMD version echo line this layout does not carry.
HEADER = """# isochrones based on PARSEC release v1.2S +  COLIBRI S_37 + S_35 + PR16
# Basic references: Bressan et al. (2012), MNRAS, 427, 127 + Chen et al. (2014, 2015), MNRAS, 444, 2525 + MNRAS, 452, 1068 + Tang et al. (2014), MNRAS, 445, 4287 + Marigo et al. (2017), ApJ, 835, 77 + Pastorelli al. (2019), MNRAS, 485, 5666 + Pastorelli al. (2020), MNRAS, in press
# Thermal pulse cycles included
# On RGB, assumed Reimers mass loss with efficiency eta=0.2
# LPV periods and growth rates added cf. Trabucchi et al. (2019)
# but fundamental-mode periods + transition are from Trabucchi et al. (2021)
# Photometric system: <i>UBVRIJHK</i> (cf. Maiz-Apellaniz 2006 + Bessell 1990)
# Using YBC version of bolometric corrections as in Chen et al. (2019)
# O-rich circumstellar dpmod60alox40 dust from Groenewegen (2006)
# C-rich circumstellar AMCSIC15 dust from Groenewegen (2006)
# IMF:
# Kind of output: isochrone tables
"""

# Documented column layout: readme columns (1)-(7), CMD 3.9 additions
# (label after logG; magnitudes; int_IMF, C/O, M_hec, logMdot at the end).
COLUMNS = (
    "log(age/yr) M_ini M_act logL/Lo logTe logG label "
    "U B V R I J H K int_IMF C/O M_hec logMdot"
).split()

Z_INIT = 0.0152
Y_INIT = 0.2485 + 1.78 * Z_INIT  # PARSEC enrichment law (scaled-solar)
X_INIT = 1.0 - Y_INIT - Z_INIT


def block_rows(log_age: float, n: int = 40) -> list[str]:
    m_ini = np.linspace(0.15, 2.5, n)
    # crude but plausible MS+RGB-ish relations, monotone in mass
    logte = 3.55 + 0.22 * (m_ini - 0.8) - 0.02 * m_ini**2
    logl = -0.9 + 3.9 * (m_ini - 0.8) + 0.12 * m_ini**2
    # logg from g = G M / R^2 with M in Msun, R from L and Teff
    log_r = 0.5 * (logl - 4 * (logte - np.log10(5772.0)))
    logg = np.log10(27400.0) + np.log10(m_ini) - 2 * log_r
    label = np.where(m_ini < 0.9, 1, np.where(m_ini < 1.4, 3, 4)).astype(int)
    m_act = m_ini * (1 - 0.02 * np.clip(m_ini - 0.9, 0, None))
    int_imf = 0.3 * m_ini**1.35
    co = np.where(label >= 8, 1.2, 0.55)
    m_hec = np.where(label >= 7, 0.47 * m_ini**0.5, 0.0)
    log_mdot = np.where(label >= 7, -7.0 + 0.5 * m_ini, -99.0)
    mags = []
    for offset in (-1.2, -0.4, 0.0, 0.35, 0.9, 1.4, 1.8, 2.2):
        mags.append(4.74 - 2.5 * logl + offset)
    rows = []
    for i in range(n):
        fields = [
            f"{log_age:7.3f}",
            f"{m_ini[i]:10.5f}",
            f"{m_act[i]:10.5f}",
            f"{logl[i]:9.4f}",
            f"{logte[i]:8.4f}",
            f"{logg[i]:8.4f}",
            f"{label[i]:6d}",
        ]
        fields += [f"{mags[k][i]:8.4f}" for k in range(8)]
        fields += [
            f"{int_imf[i]:11.6f}",
            f"{co[i]:6.3f}",
            f"{m_hec[i]:8.5f}",
            f"{log_mdot[i]:8.3f}",
        ]
        rows.append(" ".join(fields))
    return rows


def main() -> None:
    out = [HEADER.rstrip("\n"), "# " + " ".join(COLUMNS)]
    for log_age in (9.0, 9.5):
        # documented per-isochrone header line (readme: 'HEADER LINE: with
        # the exact age and metallicity value of the isochrone')
        out.append(
            f"# Z={Z_INIT:.4f} Y={Y_INIT:.4f} X={X_INIT:.4f} "
            f"log(age/yr)={log_age:.2f}"
        )
        out.extend(block_rows(log_age))
    dst = Path(__file__).parent / "parsec_cmd_v1p2S_fixture.dat"
    dst.write_text("\n".join(out) + "\n", encoding="ascii")
    print("wrote", dst, len(out), "lines")


if __name__ == "__main__":
    main()
