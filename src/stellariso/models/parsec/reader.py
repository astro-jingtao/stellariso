"""Parser for Padova/PARSEC CMD isochrone tables.

Reading is version-anchored: :func:`parse_parsec_cmd` reads the file's
own version echo (``# File generated by CMD <version> ...``) and
dispatches to the layout parser anchored to that version. A file whose
echo names a version with no anchored parser is refused loudly — a layout
must never be guessed across versions.

- CMD 3.9 (:func:`_read_cmd_3_9`): the layout real 3.9 outputs use. The
  composition and age are ordinary per-row columns (``Zini MH logAge``),
  the masses are ``Mini`` (initial) and ``Mass`` (current), and every
  isochrone block is introduced by a REPEATED column-name comment line —
  there are no per-block ``Z=/Y=/X=`` header lines — with the file ending
  on ``#isochrone terminated``. The ``X``/``Y`` columns are the current
  surface fractions (``Y`` drifts along the isochrone; at the ZAMS it
  equals the initial helium of the enrichment law).
- The documented layout (:func:`_read_cmd_documented`): the older
  "TABLES OF ISOCHRONES" layout of the Girardi isochrone readme —
  ``log(age/yr)``, ``M_ini``, ``M_act``, ... — with per-isochrone
  ``Z=/Y=/X=`` block headers and no version echo. Kept for older CMD
  outputs; identified by its ``M_ini``/``M_act`` column signature.

Both parsers are column-name driven — names are read from the file's own
column-name line(s), so column reordering does not silently misread
data — and both cross-check each block's homogeneity (one age — and for
3.9 one Zini — per block, loud error otherwise).
"""

from __future__ import annotations

import gzip
import os
import re
from dataclasses import dataclass, field
from pathlib import Path
from typing import TextIO

import numpy as np
from astropy.table import Table

from stellariso.exceptions import (
    DataIntegrityError,
    UnrecognizedFormatError,
    UnsupportedReleaseError,
)
from stellariso.native import NativeTable

__all__ = ["ParsecFile", "parse_parsec_cmd", "open_parsec_text"]

_RELEASE_RE = re.compile(r"isochrones based on PARSEC release\s+(.+?)\s*$", re.M)
_ETA_RE = re.compile(r"Reimers mass loss with efficiency eta=(\S+)")
_PHOTSYS_RE = re.compile(r"Photometric system:\s*<i>(.*?)</i>", re.S)
_CMD_VERSION_RE = re.compile(r"^#\s*File generated by CMD (\d+(?:\.\d+)?)", re.M)
_IMF_RE = re.compile(r"^#\s*IMF:\s*(.+?)\s*$", re.M)
_KIND_RE = re.compile(r"^#\s*Kind of output:\s*(.+?)\s*$", re.M)
_BLOCK_Z_RE = re.compile(r"\bZ=([0-9.eE+-]+)")
_BLOCK_Y_RE = re.compile(r"\bY=([0-9.eE+-]+)")
_BLOCK_X_RE = re.compile(r"\bX=([0-9.eE+-]+)")


@dataclass
class ParsecBlock:
    """One isochrone block (extents index the compacted native table)."""

    header_lines: tuple[str, ...]
    row_start: int
    row_stop: int
    z: float | None = None
    y: float | None = None
    x: float | None = None
    mh: float | None = None

    @property
    def n_rows(self) -> int:
        return self.row_stop - self.row_start


@dataclass
class ParsecFile:
    native: NativeTable
    blocks: tuple[ParsecBlock, ...] = ()
    facts: dict = field(default_factory=dict)
    #: registry product key of the layout that parsed this file
    format: str = "cmd_table"


def open_parsec_text(source: str | os.PathLike | TextIO) -> tuple[TextIO, bool]:
    if hasattr(source, "read"):
        return source, False
    path = Path(source)
    if not path.exists():
        raise FileNotFoundError(path)
    if path.suffix == ".gz" or _is_gzip_content(path):
        # the CMD server force-gzips outputs above 50 MB regardless of the
        # requested output_gzip, so gzip is detected by content too
        return gzip.open(path, mode="rt", encoding="utf-8", errors="replace"), True
    return open(path, mode="r", encoding="utf-8", errors="replace"), False


def _is_gzip_content(path: Path) -> bool:
    with open(path, "rb") as raw:
        return raw.read(2) == b"\x1f\x8b"


def _looks_like_columns_documented(tokens: list[str]) -> bool:
    return "M_ini" in tokens and "M_act" in tokens


def _looks_like_columns_3_9(tokens: list[str]) -> bool:
    return "Zini" in tokens and "Mini" in tokens and "logAge" in tokens


class _BlockAccumulator:
    """Collects (header lines, data rows) groups in file order."""

    def __init__(self) -> None:
        self.groups: list[dict] = []
        self._current: dict | None = None

    def comment(self, line: str) -> None:
        if self._current is None or self._current["rows"]:
            self._current = {"hdr": [line], "rows": []}
            self.groups.append(self._current)
        else:
            self._current["hdr"].append(line)

    def data(self, parts: list[str]) -> None:
        if self._current is None:
            self._current = {"hdr": [], "rows": []}
            self.groups.append(self._current)
        self._current["rows"].append(parts)

    def finish(self) -> list[dict]:
        return [g for g in self.groups if g["rows"]]


def _header_facts(header_text: str) -> dict:
    facts: dict = {}
    m = _RELEASE_RE.search(header_text)
    facts["release"] = m.group(1).strip() if m else None
    m = _ETA_RE.search(header_text)
    facts["eta_reimers"] = float(m.group(1)) if m else None
    m = _PHOTSYS_RE.search(header_text)
    facts["photsys"] = m.group(1).strip() if m else None
    return facts


def _require_columns(columns: list[str], required: tuple[str, ...], what: str) -> None:
    for name in required:
        if name not in columns:
            raise UnrecognizedFormatError(
                f"{what}: required column {name!r} absent from the "
                f"column-name line"
            )


def _unique_rounded(values: np.ndarray, what: str, rows: str) -> float:
    unique = np.unique(np.round(values, 6))
    if len(unique) != 1:
        raise DataIntegrityError(
            f"isochrone block at rows {rows} spans {len(unique)} "
            f"distinct {what}"
        )
    return float(unique[0])


# -- CMD 3.9 (the layout real outputs use) -------------------------------------


def _read_cmd_3_9(text: str) -> ParsecFile:
    """Parse a real CMD 3.9 isochrone table (anchored to the 3.9 echo)."""
    m = _KIND_RE.search(text)
    if m is not None and m.group(1) != "isochrone tables":
        raise UnrecognizedFormatError(
            f"CMD 3.9 output is {m.group(1)!r}, not 'isochrone tables'; "
            "the isochrone reader refuses non-table outputs"
        )

    lines = text.splitlines()
    header_lines: list[str] = []
    columns: list[str] | None = None
    column_line_text: str | None = None
    acc = _BlockAccumulator()

    for line in lines:
        if line.startswith("#"):
            if columns is None:
                tokens = line.lstrip("#").split()
                if _looks_like_columns_3_9(tokens):
                    columns = tokens
                    column_line_text = line
                else:
                    header_lines.append(line)
            else:
                acc.comment(line)
            continue
        if not line.strip():
            continue
        if columns is None:
            raise UnrecognizedFormatError(
                "data rows before any column-name line; not a CMD 3.9 "
                "isochrone table?"
            )
        acc.data(line.split())

    if columns is None:
        raise UnrecognizedFormatError(
            "no CMD 3.9 column-name line (Zini/Mini/logAge signature) "
            "found; not a CMD 3.9 isochrone table?"
        )
    _require_columns(
        columns,
        ("Zini", "MH", "logAge", "Mini", "int_IMF", "Mass", "logL", "logTe",
         "logg", "label"),
        "CMD 3.9 table",
    )
    # McoreTP / C_O / the LPV columns exist only when the TP-AGB is
    # included (COLIBRI products); outputs without it legitimately lack
    # them, and the corresponding unified fields are then absent too
    age_col = columns.index("logAge")
    z_col = columns.index("Zini")
    mh_col = columns.index("MH")

    groups = acc.finish()
    if groups and not (
        groups[0]["hdr"] and groups[0]["hdr"][0].lstrip("#").split() == columns
    ):
        # the first block is introduced by the file-level column line
        groups[0]["hdr"].insert(0, "#" + column_line_text.lstrip("#"))
    arr = np.array(
        [[float(v) for v in row] for g in groups for row in g["rows"]],
        dtype=np.float64,
    )
    if arr.size == 0:
        raise UnrecognizedFormatError(
            "no data rows (a header-only CMD 3.9 table is the form's "
            "silent failure mode for mismatched payloads)"
        )

    blocks: list[ParsecBlock] = []
    ages: list[float] = []
    row_cursor = 0
    for g in groups:
        start, stop = row_cursor, row_cursor + len(g["rows"])
        row_cursor = stop
        rows = arr[start:stop]
        for j, parts in enumerate(g["rows"]):
            if len(parts) != len(columns):
                raise DataIntegrityError(
                    f"row {start + j} has {len(parts)} fields, the column "
                    f"line declares {len(columns)}"
                )
        # every block must restate the file's own column line
        block_columns = [
            ln.lstrip("#").split() for ln in g["hdr"] if ln.lstrip("#").split()
        ]
        if block_columns and block_columns[0] != columns:
            raise DataIntegrityError(
                f"isochrone block at rows {start}:{stop} declares columns "
                f"{block_columns[0]} while the file declares {columns}"
            )
        blocks.append(
            ParsecBlock(
                header_lines=tuple(g["hdr"]),
                row_start=start,
                row_stop=stop,
                z=_unique_rounded(rows[:, z_col], "Zini", f"{start}:{stop}"),
                mh=_unique_rounded(rows[:, mh_col], "MH", f"{start}:{stop}"),
            )
        )
        ages.append(_unique_rounded(rows[:, age_col], "logAge", f"{start}:{stop}"))

    header_text = "\n".join(header_lines)
    facts = _header_facts(header_text)
    facts["cmd_version"] = _CMD_VERSION_RE.search(text).group(1)
    facts["ages"] = tuple(ages)
    m = _IMF_RE.search(text)
    facts["imf"] = m.group(1).strip() if m else None

    table = Table(arr, names=list(columns))
    native = NativeTable(
        table=table,
        header=tuple(header_lines),
        metadata={k: v for k, v in facts.items() if k != "ages"},
        block_metadata=tuple(
            {"log_age": a, "z": b.z, "y": b.y, "x": b.x, "mh": b.mh}
            for a, b in zip(ages, blocks)
        ),
    )
    return ParsecFile(native=native, blocks=tuple(blocks), facts=facts,
                      format="cmd_table_3_9")


# -- the documented (readme) layout ---------------------------------------------


def _read_cmd_documented(text: str) -> ParsecFile:
    """Parse the older documented layout (no version echo in these files)."""
    lines = text.splitlines()
    header_lines: list[str] = []
    columns: list[str] | None = None
    acc = _BlockAccumulator()

    for line in lines:
        if line.startswith("#"):
            if columns is None:
                tokens = line.lstrip("#").split()
                if _looks_like_columns_documented(tokens):
                    columns = tokens
                else:
                    header_lines.append(line)
            else:
                acc.comment(line)
            continue
        if not line.strip():
            continue
        if columns is None:
            raise UnrecognizedFormatError(
                "data rows before any column-name line; not a CMD isochrone table?"
            )
        acc.data(line.split())

    if columns is None:
        raise UnrecognizedFormatError(
            "no column-name line (M_ini/M_act signature) found; "
            "not a CMD isochrone table?"
        )
    for name in ("M_ini", "logTe", "logG"):
        if name not in columns:
            raise UnrecognizedFormatError(
                f"required column {name!r} absent from column-name line"
            )
    age_name = "log(age/yr)"
    if age_name not in columns:
        raise UnrecognizedFormatError(f"column {age_name!r} not found")
    age_col = columns.index(age_name)

    groups = acc.finish()
    arr = np.array(
        [[float(v) for v in row] for g in groups for row in g["rows"]],
        dtype=np.float64,
    )
    if arr.size == 0:
        raise UnrecognizedFormatError("no data rows")

    blocks: list[ParsecBlock] = []
    ages: list[float] = []
    row_cursor = 0
    for g in groups:
        start, stop = row_cursor, row_cursor + len(g["rows"])
        row_cursor = stop
        rows = arr[start:stop]
        for j, parts in enumerate(g["rows"]):
            if len(parts) != len(columns):
                raise DataIntegrityError(
                    f"row {start + j} has {len(parts)} fields, column line "
                    f"declares {len(columns)}"
                )
        ages.append(_unique_rounded(rows[:, age_col], "age", f"{start}:{stop}"))
        hdr_text = "\n".join(g["hdr"])
        blocks.append(
            ParsecBlock(
                header_lines=tuple(g["hdr"]),
                row_start=start,
                row_stop=stop,
                z=_first(_BLOCK_Z_RE, hdr_text),
                y=_first(_BLOCK_Y_RE, hdr_text),
                x=_first(_BLOCK_X_RE, hdr_text),
            )
        )

    header_text = "\n".join(header_lines)
    facts = _header_facts(header_text)
    facts["ages"] = tuple(ages)

    table = Table(arr, names=list(columns))
    native = NativeTable(
        table=table,
        header=tuple(header_lines),
        metadata={k: v for k, v in facts.items() if k != "ages"},
        block_metadata=tuple(
            {"log_age": a, "z": b.z, "y": b.y, "x": b.x}
            for a, b in zip(ages, blocks)
        ),
    )
    return ParsecFile(native=native, blocks=tuple(blocks), facts=facts,
                      format="cmd_table")


def _first(regex: re.Pattern, text: str) -> float | None:
    m = regex.search(text)
    return float(m.group(1)) if m else None


# -- dispatch --------------------------------------------------------------------


def parse_parsec_cmd(source: str | os.PathLike | TextIO) -> ParsecFile:
    """Parse one CMD isochrone table, anchored to its own version echo.

    A ``# File generated by CMD <version>`` line dispatches to that
    version's parser; a version with no parser is a loud
    :class:`UnsupportedReleaseError`. Files without the echo are accepted
    only when they carry the documented layout's ``M_ini``/``M_act``
    column signature.
    """
    fh, opened = open_parsec_text(source)
    try:
        text = fh.read()
    finally:
        if opened:
            fh.close()

    m = _CMD_VERSION_RE.search(text)
    if m is not None:
        version = m.group(1)
        if version == "3.9":
            return _read_cmd_3_9(text)
        raise UnsupportedReleaseError(
            f"CMD version {version} has no anchored reader; implemented: "
            "3.9 (plus the pre-echo documented layout)"
        )
    for line in text.splitlines():
        if line.startswith("#"):
            tokens = line.lstrip("#").split()
            if _looks_like_columns_documented(tokens):
                return _read_cmd_documented(text)
    raise UnrecognizedFormatError(
        "no CMD version echo and no documented-layout column line; "
        "not a CMD isochrone table?"
    )
